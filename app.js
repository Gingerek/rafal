const state = { lang: "nl", collection: null, index: 0 };
const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];

function t(key) { return translations[state.lang]?.[key] || translations.en[key] || key; }
function imagePath(file) { return `images/${file.split("/").map(encodeURIComponent).join("/")}`; }

function updateLanguage() {
  document.documentElement.lang = state.lang;
  $$('[data-i18n]').forEach(node => { const value = t(node.dataset.i18n); if (value) node.textContent = value; });
  $$('[data-lang]').forEach(button => button.classList.toggle('active', button.dataset.lang === state.lang));
  const url = new URL(location.href);
  url.searchParams.set('lang', state.lang);
  history.replaceState(null, '', `${url.pathname}${url.search}${url.hash}`);
  document.title = state.lang === 'pl' ? 'FotodiSogno — Fotografia Rafała Wilka' : state.lang === 'nl' ? 'FotodiSogno — Fotografie door Rafał Wilk' : 'FotodiSogno — Photography by Rafał Wilk';
  renderCollections();
  if (state.collection) updateModalText();
}

function renderCollections() {
  const grid = $('#collectionGrid');
  grid.innerHTML = '';
  collections.forEach(collection => {
    const button = document.createElement('button');
    button.className = 'collection-card reveal';
    button.type = 'button';
    button.dataset.openCollection = collection.id;
    button.innerHTML = `
      <img src="${imagePath(collection.cover)}" alt="${t(collection.titleKey)}" loading="lazy" decoding="async">
      <span class="collection-card-content">
        <h4>${t(collection.titleKey)}</h4>
        <p>${t(collection.descKey)}</p>
      </span>`;
    grid.appendChild(button);
  });
  observeReveals();
}

function openCollection(id) {
  const collection = collections.find(item => item.id === id);
  if (!collection) return;
  state.collection = collection;
  state.index = 0;
  updateModalText();
  const gallery = $('#masonryGallery');
  gallery.innerHTML = '';
  collection.items.forEach(([src, alt], index) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'gallery-button';
    button.dataset.photoIndex = index;
    button.setAttribute('aria-label', alt);
    button.innerHTML = `<img src="${imagePath(src)}" alt="${alt}" loading="lazy" decoding="async">`;
    gallery.appendChild(button);
  });
  $('#collectionModal').classList.add('open');
  $('#collectionModal').setAttribute('aria-hidden', 'false');
  document.body.classList.add('overlay-open');
  requestAnimationFrame(() => $('#collectionModal .collection-dialog').focus());
}

function updateModalText() {
  if (!state.collection) return;
  $('#collectionTitle').textContent = t(state.collection.titleKey);
  $('#collectionDescription').textContent = t(state.collection.descKey);
}

function closeCollection() {
  $('#collectionModal').classList.remove('open');
  $('#collectionModal').setAttribute('aria-hidden', 'true');
  document.body.classList.remove('overlay-open');
  state.collection = null;
}

function openLightbox(index) {
  if (!state.collection) return;
  state.index = index;
  showLightboxPhoto();
  $('#lightbox').classList.add('open');
  $('#lightbox').setAttribute('aria-hidden', 'false');
}

function showLightboxPhoto() {
  const [src, alt] = state.collection.items[state.index];
  const image = $('#lightboxImage');
  image.src = imagePath(src);
  image.alt = alt;
  $('#lightboxCaption').textContent = alt;
  $('#lightboxCounter').textContent = `${state.index + 1} / ${state.collection.items.length}`;
}

function closeLightbox() {
  $('#lightbox').classList.remove('open');
  $('#lightbox').setAttribute('aria-hidden', 'true');
  $('#lightboxImage').src = '';
}

function movePhoto(direction) {
  if (!state.collection) return;
  const total = state.collection.items.length;
  state.index = (state.index + direction + total) % total;
  showLightboxPhoto();
}

let revealObserver;
function observeReveals() {
  const items = $$('.reveal:not(.reveal-observed)');
  if (matchMedia('(prefers-reduced-motion: reduce)').matches || !('IntersectionObserver' in window)) {
    items.forEach(item => item.classList.add('visible'));
    return;
  }
  if (!revealObserver) {
    revealObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          revealObserver.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: .08 });
  }
  items.forEach(item => { item.classList.add('reveal-observed'); revealObserver.observe(item); });
}

function closeMenu() {
  $('#siteNav').classList.remove('open');
  $('#menuToggle').setAttribute('aria-expanded', 'false');
}

function init() {
  const requested = new URL(location.href).searchParams.get('lang');
  state.lang = translations[requested] ? requested : 'nl';
  $('#year').textContent = new Date().getFullYear();

  updateLanguage();
  $$('.section-heading, .featured, .collections-header, .about-image-wrap, .about-copy, .contact-copy, .contact-actions').forEach(node => node.classList.add('reveal'));
  observeReveals();

  $$('[data-lang]').forEach(button => button.addEventListener('click', () => { state.lang = button.dataset.lang; updateLanguage(); }));
  document.addEventListener('click', event => {
    const opener = event.target.closest('[data-open-collection]');
    if (opener) openCollection(opener.dataset.openCollection);
    const photo = event.target.closest('[data-photo-index]');
    if (photo) openLightbox(Number(photo.dataset.photoIndex));
  });

  $('#closeCollection').addEventListener('click', closeCollection);
  $('#closeLightbox').addEventListener('click', closeLightbox);
  $('#prevPhoto').addEventListener('click', () => movePhoto(-1));
  $('#nextPhoto').addEventListener('click', () => movePhoto(1));
  $('#collectionModal').addEventListener('click', event => { if (event.target === $('#collectionModal')) closeCollection(); });
  $('#lightbox').addEventListener('click', event => { if (event.target === $('#lightbox')) closeLightbox(); });

  $('#menuToggle').addEventListener('click', () => {
    const open = !$('#siteNav').classList.contains('open');
    $('#siteNav').classList.toggle('open', open);
    $('#menuToggle').setAttribute('aria-expanded', String(open));
  });
  $$('.main-nav a').forEach(link => link.addEventListener('click', closeMenu));

  window.addEventListener('scroll', () => $('#siteHeader').classList.toggle('scrolled', scrollY > 18), { passive: true });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape') {
      if ($('#lightbox').classList.contains('open')) closeLightbox();
      else if ($('#collectionModal').classList.contains('open')) closeCollection();
      else closeMenu();
    }
    if ($('#lightbox').classList.contains('open') && event.key === 'ArrowLeft') movePhoto(-1);
    if ($('#lightbox').classList.contains('open') && event.key === 'ArrowRight') movePhoto(1);
  });
}

document.addEventListener('DOMContentLoaded', init);
